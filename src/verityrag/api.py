"""
FastAPI service exposing the pipeline in real time.

  GET  /        -> service info + links (so hitting the base URL isn't a 404)
  POST /ingest   -> add a document to the live index immediately
  POST /query    -> run the agent controller and return a grounded answer
                     (or an explicit abstention) + full trace for observability
  GET  /health   -> liveness probe
  GET  /stats    -> index size, reranker status -- what you'd wire to a
                     dashboard in production

Interactive API docs (Swagger UI) are auto-generated by FastAPI at /docs --
useful for calling /ingest and /query by hand without curl/Postman.
"""
from __future__ import annotations

import os

from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field

from .pipeline import VerityRAGPipeline

app = FastAPI(title="VerityRAG", version="0.1.0")
# Browser front ends call this API cross-origin (the React dev server runs on :5173).
# Set VERITYRAG_CORS_ORIGINS to a comma-separated list to allow other origins.
app.add_middleware(
    CORSMiddleware,
    allow_origins=[o.strip() for o in os.environ.get(
        "VERITYRAG_CORS_ORIGINS", "http://localhost:5173,http://127.0.0.1:5173").split(",") if o.strip()],
    allow_methods=["GET", "POST"],
    allow_headers=["*"],
)
pipeline = VerityRAGPipeline()


class IngestRequest(BaseModel):
    doc_id: str = Field(max_length=200)
    title: str = Field(max_length=200)
    text: str = Field(max_length=5000)


class QueryRequest(BaseModel):
    question: str = Field(max_length=500)


class ClaimOut(BaseModel):
    claim: str
    semantic_support: float
    lexical_support: float
    is_grounded: bool


class StepOut(BaseModel):
    hop: int
    query_used: str
    n_candidates: int
    top_score: float
    action: str


class EvidenceOut(BaseModel):
    chunk_id: str
    doc_id: str
    title: str
    text: str
    dense_score: float


class PartOut(BaseModel):
    """One sub-question of a compound question and what each agent did with it."""
    sub_question: str
    answer: str | None
    abstained: bool
    abstain_reason: str | None
    grounding_score: float | None
    evidence_chunk_ids: list[str]
    retriever_steps: list[StepOut]
    verifier_steps: list[StepOut]


class QueryResponse(BaseModel):
    question: str
    answer: str | None
    abstained: bool
    grounding_score: float | None
    verdict: str | None
    claims: list[ClaimOut]
    evidence_chunk_ids: list[str]
    hops_used: int
    # Which layer refused ("sufficiency" | "answerability" | "grounding" | "guard"), else null.
    abstain_reason: str | None = None
    # Sub-questions the planner found (empty for a single question) and per-part detail.
    plan: list[str] = Field(default_factory=list)
    parts: list[PartOut] = Field(default_factory=list)
    trace: list[StepOut] = Field(default_factory=list)
    evidence: list[EvidenceOut] = Field(default_factory=list)


def _step(s) -> StepOut:
    return StepOut(hop=s.hop, query_used=s.query_used, n_candidates=s.n_candidates,
                   top_score=s.top_score, action=s.action)


@app.get("/")
def root():
    return {
        "service": "VerityRAG",
        "version": "0.1.0",
        "description": "Real-time agentic RAG with grounding & hallucination detection",
        "docs": "/docs",
        "endpoints": {
            "POST /ingest": "add a document to the live index",
            "POST /query": "ask a question, get a grounded answer or an explicit abstention",
            "GET /health": "liveness probe",
            "GET /stats": "index size and reranker status",
        },
    }


@app.post("/ingest")
def ingest(req: IngestRequest):
    n_chunks = pipeline.ingest_document(req.doc_id, req.title, req.text)
    return {"doc_id": req.doc_id, "chunks_added": n_chunks, "index_size": pipeline.index.size()}


@app.post("/query", response_model=QueryResponse)
def query(req: QueryRequest):
    result = pipeline.query(req.question)
    claims = []
    grounding_score = None
    verdict = None
    if result.grounding is not None:
        grounding_score = result.grounding.overall_score
        verdict = result.grounding.verdict
        claims = [
            ClaimOut(claim=c.claim, semantic_support=c.semantic_support,
                      lexical_support=c.lexical_support, is_grounded=c.is_grounded)
            for c in result.grounding.claims
        ]
    return QueryResponse(
        question=result.query,
        answer=result.answer,
        abstained=result.abstained,
        grounding_score=grounding_score,
        verdict=verdict,
        claims=claims,
        evidence_chunk_ids=[e.chunk_id for e in result.evidence],
        hops_used=result.hops_used,
        abstain_reason=result.abstain_reason,
        plan=list(getattr(result, "plan", [])),
        parts=[
            PartOut(sub_question=p.sub_question, answer=p.answer, abstained=p.abstained,
                    abstain_reason=p.abstain_reason, grounding_score=p.grounding_score,
                    evidence_chunk_ids=p.evidence_chunk_ids,
                    retriever_steps=[_step(s) for s in p.retriever_steps],
                    verifier_steps=[_step(s) for s in p.verifier_steps])
            for p in getattr(result, "parts", [])
        ],
        trace=[_step(s) for s in result.trace],
        evidence=[EvidenceOut(chunk_id=e.chunk_id, doc_id=e.doc_id, title=e.title,
                              text=e.text, dense_score=e.dense_score) for e in result.evidence],
    )


@app.get("/health")
def health():
    return {"status": "ok", "index_size": pipeline.index.size()}


@app.get("/stats")
def stats():
    return {
        "index_size": pipeline.index.size(),
        "reranker_trained": pipeline._reranker_model is not None,
        "index_updates_count": pipeline.index.updates_count,
    }